using System;
using TEngine;
using TMPro;
using UnityEngine.UI;

namespace GameLogic
{
    /// <summary>固定1080×1920预制体窗口；仅绑定显示与点击，不承担玩法、存档或机型适配。</summary>
    [Window(UILayer.UI, location: "UIRodLoading")]
    public sealed class UIRodLoading : UIWindow
    {
        /// <summary>将节点路径交给调用方处理业务；窗口只持有自身生命周期内的订阅。</summary>
        public event Action<string> Clicked;
        private TextMeshProUGUI _text0;
        private TextMeshProUGUI _caption;

        protected override void ScriptGenerator()
        {
            _text0 = FindChildComponent<TextMeshProUGUI>("Panel/LoadingPercent");
            _caption = FindChildComponent<TextMeshProUGUI>("Panel/LoadingCaption");
        }

        /// <summary>按节点路径更新文案，使用已缓存组件，不重建层级。</summary>
        public bool SetText(string path, string value)
        {
            switch (path)
            {
                case "Panel/LoadingPercent": _text0.text = value; return true;
                case "Panel/LoadingCaption": _caption.text = value; return true;
                default: return false;
            }
        }

        /// <summary>关闭时释放外部业务订阅，缓存窗口再次打开由调用方重新订阅。</summary>
        protected override void OnClose()
        {
            Clicked = null;
            base.OnClose();
        }
    }
}
